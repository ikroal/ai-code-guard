"""Claude Code Agent adapter implementation.

Claude Code supports full Hook capability:
- PreToolUse Hook for runtime interception (can_block=True)
- User confirmation prompts (can_ask=True)

Rule document: CLAUDE.md
Hook entry: .claude/hooks/interceptor.py (stdin/stdout JSON)
"""

from __future__ import annotations

from ai_guard.adapters.base import AgentAdapter, AgentCapabilities
from ai_guard.config.models import BehaviorConfig
from ai_guard.shared.types import FileSpec, wrap_with_managed_block

__all__ = ["ClaudeCodeAdapter"]


class ClaudeCodeAdapter(AgentAdapter):
    """Adapter for Claude Code AI coding agent."""

    @property
    def name(self) -> str:
        return "claude-code"

    @property
    def capabilities(self) -> AgentCapabilities:
        return AgentCapabilities(can_block=True, can_ask=True)

    def rule_doc_path(self) -> str:
        return "CLAUDE.md"

    def render_rule_doc(self, behavior: BehaviorConfig) -> str:
        """Render behavior rules as Claude Code rule document.

        Output format is Markdown wrapped with managed block markers.
        WP1.3b will add Jinja2 templates for improved formatting.
        """
        lines: list[str] = []

        # Header
        lines.append("## Behavior Constraints")
        lines.append("")
        lines.append(
            "The following rules define what operations are permitted, "
            "blocked, or require approval."
        )
        lines.append("")

        # Render each operation type
        for op_name, op_rules in [
            ("Read", behavior.read),
            ("Write", behavior.write),
            ("Execute", behavior.execute),
        ]:
            lines.append(f"### {op_name} Operations")
            lines.append("")

            if op_rules.forbidden:
                lines.append("**Forbidden** (blocked):")
                for rule in op_rules.forbidden:
                    reason = f" — {rule.reason}" if rule.reason else ""
                    lines.append(f"- `{rule.pattern}`{reason}")
                lines.append("")

            if op_rules.require_approval:
                lines.append("**Require Approval** (ask user):")
                for rule in op_rules.require_approval:
                    msg = f" — {rule.message}" if rule.message else ""
                    lines.append(f"- `{rule.pattern}`{msg}")
                lines.append("")

            if op_rules.allow:
                lines.append("**Allowed** (permitted):")
                for rule in op_rules.allow:
                    lines.append(f"- `{rule.pattern}`")
                lines.append("")

        content = "\n".join(lines)
        return wrap_with_managed_block(content)

    def hook_files(self, behavior: BehaviorConfig) -> list[FileSpec]:
        """Generate Claude Code Hook script.

        Returns a Python Hook script that:
        - Reads stdin JSON (tool_name, tool_input)
        - Calls Enforcer for policy decision
        - Returns stdout JSON (hookSpecificOutput.permissionDecision)

        WP1.3b will add full protocol conversion template.
        """
        hook_content = '''"""Claude Code PreToolUse Hook for AI Guard.

Generated by ai-guard install --agent claude-code.
This file is managed by AI Guard — do not edit manually.
"""

import json
import sys

def main():
    # Read tool call from stdin
    input_data = json.load(sys.stdin)
    tool_name = input_data.get("tool_name", "")
    tool_input = input_data.get("tool_input", {})

    # TODO: Call Enforcer for policy decision (WP2)
    # For now, allow all operations
    decision = "allow"

    # Output Claude Code expected format
    output = {
        "hookSpecificOutput": {
            "permissionDecision": decision
        }
    }
    json.dump(output, sys.stdout)

if __name__ == "__main__":
    main()
'''

        return [
            FileSpec(
                path=".claude/hooks/interceptor.py",
                content=hook_content,
                executable=True,
            ),
        ]
